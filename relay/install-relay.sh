#!/bin/sh
# Install the Tellico relay on the gateway host.
#
# The relay is how a user follows and steers their own OpenCode sessions from
# a phone: every opencode-tellico launched with remote control on publishes its
# sessions here, and the phone signs in with the same gateway key. See
# relay/README.md.
#
# It reads the gateway's keys file and serves under /tellico/ on the same
# hostname, so it goes on the host the gateway runs on. It never restarts the
# gateway, the tunnel or the reverse proxy, so sessions in flight -- anyone's
# -- are untouched while this runs. Restarting the relay itself only makes
# every connected plugin resend its sessions a few seconds later.
set -eu

repo_dir=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
config_home=${XDG_CONFIG_HOME:-"$HOME/.config"}
gateway_dir="$config_home/tellico-gateway"
config_dir="$config_home/tellico-relay"
env_file="$config_dir/relay.env"
lib_dir="$HOME/.local/lib/tellico-relay"
bin_dir="$HOME/.local/bin"
unit_dir="$config_home/systemd/user"
unit_name=tellico-relay.service

start=1
want_bind=''
want_port=''

usage() {
  cat >&2 <<'USAGE'
usage: relay/install-relay.sh [options]

  --bind ADDR   address to listen on (default: 127.0.0.1)
  --port PORT   port to listen on (default: 4100)
  --no-start    install files only; do not (re)start the service
USAGE
  exit 2
}

while [ $# -gt 0 ]; do
  case $1 in
    --bind) want_bind=${2:?--bind needs a value}; shift 2 ;;
    --port) want_port=${2:?--port needs a value}; shift 2 ;;
    --no-start) start=0; shift ;;
    -h|--help) usage ;;
    *) echo "install-relay.sh: unknown option $1" >&2; usage ;;
  esac
done

fail() {
  echo "install-relay.sh: $1" >&2
  shift
  for line in "$@"; do
    echo "  $line" >&2
  done
  exit 1
}

command -v python3 >/dev/null 2>&1 || fail 'python3 is required but not on PATH.'

[ -r "$gateway_dir/gateway.env" ] ||
  fail 'the gateway is not installed on this host.' \
    'The relay signs users in with gateway keys, so it lives beside the gateway:' \
    '  gateway/install-gateway.sh' \
    'Then rerun this script.'

if [ -r "$env_file" ]; then
  # shellcheck disable=SC1090
  . "$env_file"
fi
# shellcheck disable=SC1090
. "$gateway_dir/gateway.env"

bind=${want_bind:-${TELLICO_RELAY_BIND:-127.0.0.1}}
port=${want_port:-${TELLICO_RELAY_PORT:-4100}}
keys=${TELLICO_GATEWAY_KEYS:-$gateway_dir/keys}

case $port in ''|*[!0-9]*) fail "--port must be a number, got '$port'" ;; esac
case $bind in
  127.0.0.1|localhost|::1) ;;
  *) echo 'install-relay.sh: warning: the relay has no TLS of its own; keep it on loopback behind the proxy.' >&2 ;;
esac

umask 022
mkdir -p "$lib_dir/web" "$bin_dir"
install -m 0644 "$repo_dir/relay/tellico_relay.py" "$lib_dir/tellico_relay.py"
# The web app is replaced whole, so a file removed upstream does not linger.
rm -f "$lib_dir/web/"*
for file in "$repo_dir"/relay/web/*; do
  install -m 0644 "$file" "$lib_dir/web/$(basename "$file")"
done
install -m 0755 "$repo_dir/relay/bin/tellico-relay" "$bin_dir/tellico-relay"
echo "Installed $lib_dir/tellico_relay.py and $(ls "$lib_dir/web" | wc -l | tr -d ' ') web files"
echo "Installed $bin_dir/tellico-relay"

mkdir -p "$config_dir"
chmod 700 "$config_dir"
# No secrets here: keys stay hashed in the gateway's file, and sign-ins are
# stored hashed in $config_dir/tokens by the relay itself.
umask 077
cat >"$env_file" <<EOF
# Generated by relay/install-relay.sh. Edit, then: tellico-relay restart
TELLICO_RELAY_BIND="$bind"
TELLICO_RELAY_PORT="$port"
TELLICO_GATEWAY_KEYS="$keys"
TELLICO_RELAY_STATE_DIR="$config_dir"
TELLICO_RELAY_WEB="$lib_dir/web"
TELLICO_RELAY_SCRIPT="$lib_dir/tellico_relay.py"
EOF
chmod 600 "$env_file"
echo "Wrote     $env_file"

have_systemd_user() {
  command -v systemctl >/dev/null 2>&1 &&
    systemctl --user is-system-running >/dev/null 2>&1
}

if have_systemd_user; then
  umask 022
  mkdir -p "$unit_dir"
  sed \
    -e "s|__TELLICO_RELAY_ENV__|$env_file|g" \
    -e "s|__TELLICO_RELAY_PYTHON__|$(command -v python3)|g" \
    -e "s|__TELLICO_RELAY_SCRIPT__|$lib_dir/tellico_relay.py|g" \
    "$repo_dir/systemd/$unit_name.in" >"$unit_dir/$unit_name"
  chmod 644 "$unit_dir/$unit_name"
  systemctl --user daemon-reload
  systemctl --user enable "$unit_name" >/dev/null
  echo "Enabled   $unit_dir/$unit_name"
else
  echo 'No systemd user manager here, so the relay has no service unit.'
  echo 'Run it in the foreground (or under your own supervisor) with:'
  echo '  tellico-relay run'
  start=0
fi

if [ "$start" -eq 1 ]; then
  echo
  if ! "$bin_dir/tellico-relay" restart; then
    echo >&2
    echo 'The relay did not come up. Look at:' >&2
    echo '  journalctl --user -u tellico-relay -n 50' >&2
    exit 1
  fi
  "$bin_dir/tellico-relay" status
fi

echo
echo 'Publish it under /tellico/ on the gateway hostname. In the Caddy site'
echo 'block, above any catch-all:'
echo
echo "	@relay path /tellico /tellico/*"
echo "	handle @relay {"
echo "		reverse_proxy $bind:$port {"
echo "			flush_interval -1"
echo "		}"
echo "	}"
echo
echo 'Then each user turns it on for their own device:'
echo '  ./install.sh --no-start --remote-control'
