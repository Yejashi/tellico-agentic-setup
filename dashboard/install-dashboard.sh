#!/bin/sh
# Install the Tellico dashboard on the gateway host (dashboard/README.md).
#
# It reads the gateway's state file and journal and the tunnel's ports, so it
# goes on the host the gateway runs on. It never restarts the gateway, the
# tunnel, the relay or the reverse proxy. It listens on loopback only and is
# not published: reach it over ssh.
set -eu

repo_dir=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
config_home=${XDG_CONFIG_HOME:-"$HOME/.config"}
gateway_dir="$config_home/tellico-gateway"
config_dir="$config_home/tellico-dashboard"
env_file="$config_dir/dashboard.env"
lib_dir="$HOME/.local/lib/tellico-dashboard"
bin_dir="$HOME/.local/bin"
unit_dir="$config_home/systemd/user"
unit_name=tellico-dashboard.service

start=1
want_port=''
want_db=''

usage() {
  echo 'usage: dashboard/install-dashboard.sh [--port PORT] [--db PATH] [--no-start]' >&2
  echo '  --db PATH  keep the database outside the private config directory, group' >&2
  echo '             read-write, e.g. for Grafana (dashboard/grafana/README.md)' >&2
  exit 2
}

while [ $# -gt 0 ]; do
  case $1 in
    --port) want_port=${2:?--port needs a value}; shift 2 ;;
    --db) want_db=${2:?--db needs a path}; shift 2 ;;
    --no-start) start=0; shift ;;
    -h|--help) usage ;;
    *) echo "install-dashboard.sh: unknown option $1" >&2; usage ;;
  esac
done

fail() {
  echo "install-dashboard.sh: $1" >&2
  exit 1
}

command -v python3 >/dev/null 2>&1 || fail 'python3 is required but not on PATH.'
[ -r "$gateway_dir/gateway.env" ] || fail 'the gateway is not installed on this host: gateway/install-gateway.sh'

if [ -r "$env_file" ]; then
  # shellcheck disable=SC1090
  . "$env_file"
fi
port=${want_port:-${TELLICO_DASHBOARD_PORT:-4101}}
db=${want_db:-${TELLICO_DASHBOARD_DB:-"$config_dir/dashboard.db"}}
# Anywhere but the private default is shared (group read-write).
shared=0
[ "$db" = "$config_dir/dashboard.db" ] || shared=1
case $port in ''|*[!0-9]*) fail "--port must be a number, got '$port'" ;; esac

umask 022
mkdir -p "$lib_dir/web" "$bin_dir"
install -m 0644 "$repo_dir/dashboard/tellico_dashboard.py" "$lib_dir/tellico_dashboard.py"
rm -f "$lib_dir/web/"*
if [ -d "$repo_dir/dashboard/web" ]; then
  for file in "$repo_dir"/dashboard/web/*; do
    [ -f "$file" ] && install -m 0644 "$file" "$lib_dir/web/$(basename "$file")"
  done
fi
install -m 0755 "$repo_dir/dashboard/bin/tellico-dashboard" "$bin_dir/tellico-dashboard"
echo "Installed $lib_dir and $bin_dir/tellico-dashboard"

mkdir -p "$config_dir"
chmod 700 "$config_dir"
umask 077
cat >"$env_file" <<EOF
# Generated by dashboard/install-dashboard.sh. Edit, then: tellico-dashboard restart
TELLICO_DASHBOARD_BIND="127.0.0.1"
TELLICO_DASHBOARD_PORT="$port"
TELLICO_DASHBOARD_STATE_DIR="$config_dir"
TELLICO_DASHBOARD_DB="$db"
TELLICO_DASHBOARD_SHARED="$shared"
TELLICO_DASHBOARD_WEB="$lib_dir/web"
TELLICO_DASHBOARD_SCRIPT="$lib_dir/tellico_dashboard.py"
EOF
echo "Wrote     $env_file"

if command -v systemctl >/dev/null 2>&1 && systemctl --user is-system-running >/dev/null 2>&1; then
  umask 022
  mkdir -p "$unit_dir"
  sed \
    -e "s|__TELLICO_DASHBOARD_ENV__|$env_file|g" \
    -e "s|__TELLICO_DASHBOARD_PYTHON__|$(command -v python3)|g" \
    -e "s|__TELLICO_DASHBOARD_SCRIPT__|$lib_dir/tellico_dashboard.py|g" \
    "$repo_dir/systemd/$unit_name.in" >"$unit_dir/$unit_name"
  systemctl --user daemon-reload
  systemctl --user enable "$unit_name" >/dev/null
  echo "Enabled   $unit_dir/$unit_name"
else
  echo 'No systemd user manager here; run it with: tellico-dashboard run'
  start=0
fi

if [ "$start" -eq 1 ]; then
  "$bin_dir/tellico-dashboard" restart
  "$bin_dir/tellico-dashboard" status
fi
echo
echo 'Reach it over ssh:'
echo "  ssh <this host> tellico-dashboard report 24h"
echo "  ssh -L $port:127.0.0.1:$port <this host>   then http://127.0.0.1:$port/monitor/api/live"
